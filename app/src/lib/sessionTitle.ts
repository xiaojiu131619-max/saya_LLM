/**
 * 会话标题的模型总结。
 *
 * 会话创建时标题先落成首条用户消息的截取（见 AppContext 的 `titleFromFirstUserMessage`），
 * 首轮回答完成后再用模型总结一个更贴题的短标题替换它；用户手动改过名的会话不再覆盖。
 *
 * 这里刻意走独立的非流式请求（而不是复用 `streamChatCompletion`）：
 * - 标题请求不该干扰聊天统计（token 用量、tok/s、上下文水位都属于对话本身）；
 * - 也不该抢占主请求的 abort controller——用户停止生成时标题任务应继续跑完。
 */

/** 标题字数上限：超出直接截断，避免模型不听话时把整句塞进侧边栏。 */
export const SESSION_TITLE_MAX_CHARS = 20;

/** 首条消息截取标题的老规则上限（与 AppContext 的 AUTO_TITLE_MAX_LENGTH 保持一致）。 */
const AUTO_TITLE_SOURCE_MAX = 40;
const LEGACY_AUTO_TITLE_MAX = 24;

/** 送给模型的首条消息 / 回答的截断长度，够判断主题即可，不必全文。 */
const PROMPT_EXCERPT_MAX = 700;

const TITLE_SYSTEM_PROMPT = [
  '你给对话拟标题的工作助手。',
  '只输出标题本身：不超过 12 个汉字，不要引号、书名号、句号或任何解释。',
  '标题要概括对话实际在做什么，不要复述用户的问句。',
].join('');

/**
 * 清洗模型输出：去掉代码块、引号、前缀与多余标点，限长。
 * 返回 null 表示这段输出没法当标题用（空、全是标点、明显是解释性长句）。
 */
export function sanitizeTitle(raw: string): string | null {
  if (!raw) return null;
  let text = raw
    .replace(/```[\s\S]*?```/g, ' ')
    .replace(/^[\s>*#-]+/gm, ' ')
    .trim();
  // 只取第一行有内容的部分：模型偶尔会先写「标题：」再接正文解释。
  const firstLine = text.split(/\r?\n/).map((line) => line.trim()).find((line) => line.length > 0) ?? '';
  text = firstLine
    .replace(/^(标题|题目|主题|title)\s*[:：]\s*/i, '')
    .replace(/^[《"'“”‘’「」『』[(（]+/, '')
    .replace(/[》"'“”‘’」』\])）]+$/, '')
    .replace(/[。．.、，,；;！!？?]+$/g, '')
    .replace(/\s+/g, ' ')
    .trim();
  if (!text) return null;
  if (text.length > SESSION_TITLE_MAX_CHARS) {
    text = `${text.slice(0, SESSION_TITLE_MAX_CHARS)}…`;
  }
  return text;
}

/**
 * 当前标题是否仍是「机器自动生成的」。
 *
 * 只有自动标题才允许被模型总结替换：用户手动改过名（或改名后标题与首条消息对不上），
 * 一律保留。判定覆盖三种来源：新建会话的「新对话」、旧规则的前 24 字、新规则的 40 字截取。
 */
export function isAutoGeneratedTitle(title: string, firstUserText: string): boolean {
  const trimmedTitle = title.trim();
  if (!firstUserText.trim()) return trimmedTitle === '新对话';
  if (trimmedTitle === '新对话') return true;
  const source = firstUserText.trim().replace(/\s+/g, ' ');
  const legacy = source.slice(0, LEGACY_AUTO_TITLE_MAX);
  const current = source.length > AUTO_TITLE_SOURCE_MAX ? `${source.slice(0, AUTO_TITLE_SOURCE_MAX)}…` : source;
  return trimmedTitle === legacy || trimmedTitle === current;
}

function excerpt(text: string): string {
  const flat = text.replace(/\s+/g, ' ').trim();
  return flat.length > PROMPT_EXCERPT_MAX ? `${flat.slice(0, PROMPT_EXCERPT_MAX)}…` : flat;
}

/**
 * 用模型为一段对话总结标题。
 *
 * `port` 是本地 OpenAI 兼容端点（主模型 llama-server 或 NiNfer 引擎，两者同一条链路）。
 * 任何失败（端点没起、超时、输出不可用）都返回 null，由调用方保留原标题——
 * 标题只是显示优化，不能因为它让会话进入错误态。
 */
export async function summarizeSessionTitle(options: {
  port: number;
  modelName: string;
  apiKey?: string;
  userText: string;
  assistantText: string;
  signal?: AbortSignal;
  timeoutMs?: number;
}): Promise<string | null> {
  const { port, modelName, apiKey, userText, assistantText } = options;
  if (!modelName.trim() || !userText.trim()) return null;

  const headers: Record<string, string> = { 'Content-Type': 'application/json' };
  if (apiKey?.trim()) headers.Authorization = `Bearer ${apiKey.trim()}`;

  const controller = new AbortController();
  const timeout = window.setTimeout(() => controller.abort(), options.timeoutMs ?? 20_000);
  const onOuterAbort = () => controller.abort();
  options.signal?.addEventListener('abort', onOuterAbort);

  try {
    const response = await fetch(`http://127.0.0.1:${port}/v1/chat/completions`, {
      method: 'POST',
      headers,
      signal: controller.signal,
      body: JSON.stringify({
        model: modelName,
        stream: false,
        temperature: 0.3,
        // 思考模型可能在 64 token 内只产出思考、正文为空；给足预算并显式关闭思考
        // （不认这个字段的服务端会忽略它，行为退回普通补全）。
        max_tokens: 128,
        chat_template_kwargs: { enable_thinking: false },
        messages: [
          { role: 'system', content: TITLE_SYSTEM_PROMPT },
          {
            role: 'user',
            content: [
              '对话内容：',
              `用户：${excerpt(userText)}`,
              assistantText.trim() ? `助手：${excerpt(assistantText)}` : '',
              '',
              '请给这段对话起一个标题。',
            ].filter(Boolean).join('\n'),
          },
        ],
      }),
    });
    if (!response.ok) return null;
    const payload = await response.json() as {
      choices?: Array<{ message?: { content?: string | null } }>;
    };
    return sanitizeTitle(payload.choices?.[0]?.message?.content ?? '');
  } catch {
    return null;
  } finally {
    window.clearTimeout(timeout);
    options.signal?.removeEventListener('abort', onOuterAbort);
  }
}
